
-- PROCEDURE PARA INSERIR OS DADOS NA TABELA TB_TECNOLOGIA 

-- 


 CREATE OR REPLACE PROCEDURE PRC_INSERE_TECNOLOGIA (
 P_NOME_TECNOLOGIA IN TB_TECNOLOGIA.NOME%TYPE, 
 P_DESCRICAO       IN TB_TECNOLOGIA.DESCRICAO%TYPE )
 
 IS 
 
  BEGIN 
  
  INSERT INTO TB_TECNOLOGIA (
  ID_TECNOLOGIA,
  NOME_TECNOLOGIA,
  DESCRICAO
)

 VALUES (
 SEQ_ID_TECNOLOGIA.NEXTVAL, 
 P_NOME_TECNOLOGIA, 
 P_DESCRICAO
 
); 

 END; 
 
/ 

